import json, sys
m = json.load(open('../out/hand_meta.json'))
f = lambda v: '%.3f' % v
def vec(v): return 'HandVec(%s, %s, %s)' % tuple(f(x) for x in v)
L = []
L.append('// GENERATED from the LibHand scan by the hand bake script. Do not edit.')
L.append('//')
L.append('// LibHand hand model (c) Marin Saric, CC BY 3.0')
L.append('// (https://creativecommons.org/licenses/by/3.0/), mirrored to a left hand,')
L.append('// scaled to millimetres and its fingers slimmed to average ring sizes.')
L.append('')
L.append("part of 'hand_model.dart';")
L.append('')
L.append('/// Ring seats: little, ring, middle, index.')
L.append('const List<HandSeat> _scanSeats = [')
for k in ('1', '2', '3', '4'):
    s = m['seats'][k]
    L.append('  HandSeat(')
    L.append('    position: %s,' % vec(s['pos']))
    L.append('    normal: %s,' % vec(s['normal']))
    L.append('    along: %s,' % vec(s['along']))
    L.append('    halfWidth: %s,' % f(s['hw']))
    L.append('    bone: %d,' % m['seat_bone'][k])
    L.append('    centre: %s,' % vec(s['centre']))
    L.append('    radii: [%s],' % ', '.join(f(x) for x in s['radii']))
    L.append('  ),')
L.append('];')
L.append('')
L.append('/// Conservative capsules inside the flesh: per digit (little, ring,')
L.append('/// middle, index, thumb) three segments proximal to distal, then four')
L.append('/// down the palm.')
L.append('const List<HandBone> _scanBones = [')
for a, b, r0, r1 in m['bones']:
    L.append('  HandBone(%s, %s, %s, %s),' % (vec(a), vec(b), f(r0), f(r1)))
L.append('];')
L.append('')
L.append('/// Points on the skin all over the hand above the wrist, for framing.')
L.append('const List<double> _scanOutline = [')
for p in m['outline']:
    L.append('  %s, %s, %s,' % tuple(f(x) for x in p))
L.append('];')
L.append('')
L.append('/// Points on the four fingers, knuckles up, for framing.')
L.append('const List<double> _scanFocus = [')
for p in m['focus']:
    L.append('  %s, %s, %s,' % tuple(f(x) for x in p))
L.append('];')
L.append('')
L.append('/// A white patch of both textures that nothing on the skin maps to.')
L.append('const double _scanPatchU = %.6f, _scanPatchV = %.6f;' % tuple(m['patch']))
L.append('')
L.append('/// The forearm fades out between these heights (hand y, mm).')
L.append('const double _scanFadeStart = %s, _scanFadeEnd = %s;' % (f(m['fade'][0]), f(m['fade'][1])))
open(sys.argv[1], 'w', newline='\n').write('\n'.join(L) + '\n')
